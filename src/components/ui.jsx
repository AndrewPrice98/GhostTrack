/** Run an async loader whenever deps change. Ignores stale responses. */
export function useAsync(loader, deps) {
  const [state, setState] = useState({ loading: true, error: null, data: null })
  const [tick, setTick] = useState(0)
  // eslint-disable-next-line react-hooks/exhaustive-deps
  const load = useCallback(loader, deps)
  useEffect(() => {
    let live = true
    setState((s) => ({ ...s, loading: true, error: null }))
    load()
      .then((data) => live && setState({ loading: false, error: null, data }))
      .catch((error) => live && setState({ loading: false, error, data: null }))
    return () => { live = false }
  }, [load, tick])
  const reload = useCallback(() => setTick((t) => t + 1), [])
  return { ...state, reload, setData: (data) => setState((s) => ({ ...s, data })) }
}

function useMedia(query) {
  const get = () => (typeof window !== 'undefined' && window.matchMedia ? window.matchMedia(query).matches : false)
  const [matches, setMatches] = useState(get)
  useEffect(() => {
    if (!window.matchMedia) return undefined
    const mq = window.matchMedia(query)
    const on = () => setMatches(mq.matches)
    on()
    mq.addEventListener('change', on)
    return () => mq.removeEventListener('change', on)
  }, [query])
  return matches
}

export function useReducedMotion() {
  return useMedia('(prefers-reduced-motion: reduce)')
}

/** A value that follows `value` after it has been stable for `ms` milliseconds. */
export function useDebounced(value, ms = 250) {
  const [debounced, setDebounced] = useState(value)
  useEffect(() => {
    const t = setTimeout(() => setDebounced(value), ms)
    return () => clearTimeout(t)
  }, [value, ms])
  return debounced
}

/** A boolean kept in localStorage; every access is guarded (private mode, blocked storage). */
export function useStoredFlag(key, initial = false) {
  const [value, setValue] = useState(() => {
    try {
      const v = window.localStorage.getItem(key)
      return v === null ? initial : v === '1'
    } catch { return initial }
  })
  const set = useCallback((next) => {
    setValue(next)
    try { window.localStorage.setItem(key, next ? '1' : '0') } catch { /* not remembered */ }
  }, [key])
  return [value, set]
}

export function useWide(minWidth = 1024) {
  return useMedia(`(min-width: ${minWidth}px)`)
}

/** True while the tab is visible (Page Visibility API). */
export function usePageVisible() {
  const [visible, setVisible] = useState(() => typeof document === 'undefined' || !document.hidden)
  useEffect(() => {
    const on = () => setVisible(!document.hidden)
    document.addEventListener('visibilitychange', on)
    return () => document.removeEventListener('visibilitychange', on)
  }, [])
  return visible
}

/**
 * What to do when the database holds nothing yet. The admin gets a button to the recording upload;
 * everyone else is told how data arrives, so an empty page is never a dead end.
 */
export function EmptyCta({ what = 'data', children }) {
  const { guest } = useSession()
  return (
    <section className="card cta" aria-labelledby="cta-title">
      <h2 id="cta-title">No {what} yet</h2>
      {children && <p className="muted">{children}</p>}
      {guest ? (
        <p className="muted">
          The demo fills itself from recorded traffic with scheduled injected scenarios. If this stays empty,
          check back in a minute or <Link to="/scenarios">watch a scenario replay</Link>.
        </p>
      ) : (
        <>
          <p className="muted">Upload a recording to run the detections over it and fill this page.</p>
          <Link className="btn primary" to="/admin/upload"><Icon name="upload" size={16} /> Upload a recording</Link>
        </>
      )}
    </section>
  )
}
