export function ErrorState({ error, onRetry }) {
  if (error?.status === 503) {
    // The data routes answer 503 while the demo data is not ready (cold start, failed seed).
    return (
      <div className="state unavailable" role="alert">
        <Icon name="info" size={18} />
        <span>
          <strong>Not ready yet.</strong> {error.message || 'The data is not available yet'}. The demo prepares its data on
          first use, so this usually clears within a minute.
        </span>
        {onRetry && <button type="button" className="btn secondary small" onClick={onRetry}>Retry</button>}
      </div>
    )
  }
  return (
    <div className="state error" role="alert">
      <strong>Something went wrong.</strong> {error?.message || String(error)}
      {onRetry && <> <button type="button" className="link" onClick={onRetry}>Try again</button></>}
    </div>
  )
}

