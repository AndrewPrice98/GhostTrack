/** Compact tag: tinted background, text label, no icon and no border, so it never relies on colour alone. */
export function Chip({ tone = 'neutral', children, title, className = '' }) {
  return <span className={`chip ${tone} ${className}`} title={title}>{children}</span>
}

export function SeverityChip({ severity }) {
  const s = SEVERITY[severity] || { label: severity, tone: 'neutral' }
  return <Chip tone={`sev-${severity}`}>{s.label}<span className="sr-only"> severity</span></Chip>
}

/** Status: a 6 px dot plus the text label. */
export function StatusChip({ status }) {
  const s = STATUS[status] || { label: status, tone: 'neutral' }
  return <span className={`status status-${status}`}><span className="status-dot" aria-hidden="true" />{s.label}</span>
}

/**
 * The hatched "Injected test data" tag shown on everything that comes from a scenario. When the API
 * gives a label (for example "Injected test data (as declared by upload)") it is shown as it is.
 */
export function InjectedTag({ short = false, label }) {
  const text = injectedTagText(label, false)
  return (
    <span className="chip injected" title={`${text}: generated by a documented attack scenario or declared by an upload, not real air traffic`}>
      {injectedTagText(label, short)}
    </span>
  )
}

/** The origin label the API attaches to injected data and uploads, shown exactly as given. */
export function OriginTag({ item, short = false }) {
  const label = item?.label
  if (!label && !item?.injected) return null
  if (item.injected || /^Injected/.test(label || '')) return <InjectedTag short={short} label={label || INJECTED_LABEL} />
  return <span className="chip upload" title="Uploaded by the admin and not verified">{label}</span>
}

